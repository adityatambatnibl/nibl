"""
Shared declarative base for every table this application owns.

Everything lives in the `apqp` schema, set once on the MetaData rather than
repeated in each model, so a table can never accidentally be created in
`public` next to the other project's `users` and `improvements`.
"""

import uuid
from datetime import datetime, timezone
from typing import Any

from pydantic import BaseModel
from sqlalchemy import DateTime, MetaData, TypeDecorator
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.ext.mutable import MutableDict, MutableList
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

SCHEMA = "apqp"

# Naming convention so that autogenerated constraints get stable, readable
# names instead of whatever the backend invents - which is what makes a
# later Alembic migration able to drop them by name.
NAMING_CONVENTION = {
    "ix": "%(table_name)s_%(column_0_N_name)s_idx",
    "uq": "%(table_name)s_%(column_0_N_name)s_key",
    "fk": "%(table_name)s_%(column_0_N_name)s_fkey",
    "pk": "%(table_name)s_pkey",
}


class Base(DeclarativeBase):
    metadata = MetaData(schema=SCHEMA, naming_convention=NAMING_CONVENTION)


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class UUIDPrimaryKey:
    """
    A uuid primary key, generated in Python.

    Generating it client-side rather than leaning on the column default
    means `obj.id` is readable the moment the object exists, before any
    flush - which is what the old Beanie code relied on, since an ObjectId
    was likewise assigned up front.
    """

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )


def json_list(**kw) -> Mapped[list]:
    """A jsonb array of scalars that tracks in-place mutation."""
    return mapped_column(
        MutableList.as_mutable(JSONB), nullable=False, default=list, server_default="[]", **kw
    )


def json_dict(**kw) -> Mapped[dict]:
    """A jsonb object that tracks in-place mutation."""
    return mapped_column(
        MutableDict.as_mutable(JSONB), nullable=False, default=dict, server_default="{}", **kw
    )


def json_any(**kw) -> Mapped[Any]:
    """Nullable free-form jsonb - audit before/after snapshots."""
    return mapped_column(JSONB, nullable=True, **kw)


def ts(**kw) -> Mapped[datetime]:
    """A timezone-aware timestamp column."""
    return mapped_column(DateTime(timezone=True), **kw)


class PydanticList(TypeDecorator):
    """
    A jsonb column holding a list of Pydantic models.

    Beanie stored nested models as real objects, so roughly two dozen places
    read them by attribute - `stage.code`, `phase.activities`,
    `sorted(..., key=lambda s: s.sequence)`. Storing plain jsonb would turn
    every one of those into dictionary lookups, which is a lot of churn for
    no gain and an easy place to introduce a typo that only shows up at
    runtime.

    Converting at the column boundary instead means the database sees json
    and the application still sees typed objects, exactly as before. It also
    keeps validation honest: a row written with a missing or misspelled field
    fails on the way out, rather than surfacing as an AttributeError deep in
    a report.

    Note that in-place edits of a *nested* model (`tpl.stages[0].note = "x"`)
    are invisible to the session, as they were to Beanie. Assign the list
    back to the attribute to save changes - which is what the callers do.
    """

    impl = JSONB
    cache_ok = True

    def __init__(self, model_cls: type[BaseModel], *args, **kw):
        self.model_cls = model_cls
        super().__init__(*args, **kw)

    def process_bind_param(self, value, dialect):
        if value is None:
            return None
        out = []
        for item in value:
            if isinstance(item, BaseModel):
                # mode="json" so date and enum members become strings that
                # jsonb can actually hold.
                out.append(item.model_dump(mode="json"))
            elif isinstance(item, dict):
                out.append(item)
            else:
                raise TypeError(
                    f"{self.model_cls.__name__} list got {type(item).__name__}, "
                    "expected a model or a dict."
                )
        return out

    def process_result_value(self, value, dialect):
        if not value:
            return []
        return [self.model_cls.model_validate(v) for v in value]


def model_list(model_cls: type[BaseModel], **kw) -> Mapped[list]:
    """A jsonb list of `model_cls`, tracked for reassignment."""
    return mapped_column(
        MutableList.as_mutable(PydanticList(model_cls)),
        nullable=False,
        default=list,
        server_default="[]",
        **kw,
    )
